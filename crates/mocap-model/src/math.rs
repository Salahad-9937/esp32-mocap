//! # Базовые геометрические операции над трехмерными векторами `[f32; 3]` (`math`)

/// Трехмерный вещественный вектор координат и направлений
pub type V3 = [f32; 3];

/// Покомпонентное сложение двух векторов `a + b`.
#[inline]
#[must_use]
pub fn add(a: V3, b: V3) -> V3 {
    [a[0] + b[0], a[1] + b[1], a[2] + b[2]]
}

/// Покомпонентное вычитание двух векторов `a - b`.
#[inline]
#[must_use]
pub fn sub(a: V3, b: V3) -> V3 {
    [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
}

/// Масштабирование вектора на скаляр `a * s`.
#[inline]
#[must_use]
pub fn scale(a: V3, s: f32) -> V3 {
    [a[0] * s, a[1] * s, a[2] * s]
}

/// Умножение с накоплением `a + b * s`.
#[inline]
#[must_use]
pub fn madd(a: V3, b: V3, s: f32) -> V3 {
    [a[0] + b[0] * s, a[1] + b[1] * s, a[2] + b[2] * s]
}

/// Скалярное произведение векторов `a · b`.
#[inline]
#[must_use]
pub fn dot(a: V3, b: V3) -> f32 {
    a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
}

/// Векторное произведение `a × b` в правой системе координат.
#[inline]
#[must_use]
pub fn cross(a: V3, b: V3) -> V3 {
    [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ]
}

/// Евклидова длина вектора `|a|`.
#[inline]
#[must_use]
pub fn len(a: V3) -> f32 {
    dot(a, a).sqrt()
}

/// Евклидово расстояние между двумя точками в пространстве.
#[inline]
#[must_use]
pub fn dist(a: V3, b: V3) -> f32 {
    len(sub(a, b))
}

/// Нормализация вектора к единичной длине с защитой от деления на ноль.
#[inline]
#[must_use]
pub fn norm(a: V3) -> V3 {
    let sq = dot(a, a);
    if sq > 1e-6 {
        scale(a, 1.0 / sq.sqrt())
    } else {
        [0.0, 1.0, 0.0]
    }
}

/// Линейная интерполяция между точками `a` и `b` по параметру `t`.
#[inline]
#[must_use]
pub fn lerp(a: V3, b: V3, t: f32) -> V3 {
    [
        a[0] + (b[0] - a[0]) * t,
        a[1] + (b[1] - a[1]) * t,
        a[2] + (b[2] - a[2]) * t,
    ]
}

/// Зеркалирование вектора относительно сагиттальной плоскости X = 0.
#[inline]
#[must_use]
pub fn mirror(s: f32, p: V3) -> V3 {
    [p[0] * s, p[1], p[2]]
}